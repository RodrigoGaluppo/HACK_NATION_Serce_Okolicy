"""Explicit, offline snapshot refresh; never writes outside Lora/."""
import json
import unicodedata
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def ascii_text(s, limit):
    s = (s or '').replace('ł', 'l').replace('Ł', 'L')
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode()
    return ' '.join(s.split())[:limit]

def main():
    registry = json.loads((ROOT.parent / 'data/aed_registry.json').read_text())
    rows = [r for r in registry['items'] if r.get('latitude') and
            53.11 < r['latitude'] < 53.15 and 17.97 < r['longitude'] < 18.04
            and 'osm' in r.get('source_ids', [])]
    rows.sort(key=lambda r: (r['latitude']-53.1235)**2 + (r['longitude']-18.0084)**2)
    packets = []
    for r in rows[:8]:
        packet = dict(v=1, id=r['aed_id'], lat=r['latitude'], lon=r['longitude'],
                      n=ascii_text(r['site_name'], 32),
                      p=ascii_text(r.get('placement') or 'Lokalizacja do sprawdzenia', 44),
                      a='unverified')
        assert len(json.dumps(packet, separators=(',', ':')).encode()) <= 240
        packets.append(packet)
    if not packets:
        raise SystemExit('No matching OSM records; existing snapshot preserved')
    snapshot = dict(source='OpenStreetMap / OpenAEDMap',
                    license='ODbL-1.0', registry_generated_at=registry['generated_at'],
                    description='Offline subset; access and readiness not verified.', packets=packets)
    (ROOT/'data/bydgoszcz.json').write_text(json.dumps(snapshot, indent=2)+'\n')
    header = '#pragma once\n// Generated by tools/export_snapshot.py; OSM contributors, ODbL-1.0.\n'
    header += 'static const char* const BYDGOSZCZ[] = {\n'
    header += ''.join('  R"aed('+json.dumps(p,separators=(',', ':'))+')aed",\n' for p in packets)
    header += '};\nconstexpr size_t BYDGOSZCZ_COUNT = sizeof(BYDGOSZCZ)/sizeof(BYDGOSZCZ[0]);\n'
    (ROOT/'common/bydgoszcz.h').write_text(header)

if __name__ == '__main__':
    main()
